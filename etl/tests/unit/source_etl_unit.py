class TestIfSourceEtlRuns(unittest.TestCase):
    """
    Test that source ETL runs without errors
    """

    @classmethod
    def setUpClass(cls):
        """
        Prepare the raw source data into an S3 folder
        """
        test_name = cls.__name__
        unique_id = get_unique_id(test_name)

        cls.unittest_config_path = os.path.join(
            os.path.abspath(os.path.dirname(__file__)),
            "data/unittest_config.yaml.{}".format(unique_id),
        )

        cls.simulated_config_path = os.path.join(
            os.path.abspath(os.path.dirname(__file__)),
            "data/simulated_config.yaml.{}".format(unique_id),
        )

        templates = [
            cls.simulated_config_path,
            cls.unittest_config_path,
        ]
        for template in templates:
            original = template.replace(".{}".format(unique_id), "")
            with open(original, "r") as config_file:
                config = config_file.read()
            with open(template, "w") as config_file:
                config = config.replace("UNIQUE_ID", unique_id)
                config_file.write(config)

        prepare_etl_data(spark, cls.unittest_config_path)

    # This test is failing because of PYTHONPATH conflict.
    def test_etl_pass(self):
        """
        Run the source ETL on the test data
        """
        run_etl(self.simulated_config_path)

    @classmethod
    def tearDownClass(cls):
        """
        Delete the S3 files generated by this test
        """
        with open(cls.unittest_config_path) as config_file:
            unittest_config = yaml.load(config_file, Loader=yaml.FullLoader)

        remove_from_s3(unittest_config["root_s3_path"])



def prepare_etl_data(spark_in, unittest_config_path):
    """
    Copy the local text files from test_data/ETL/
    to an S3 folder that simulates the memberdna-data-in
    bucket.

    Args:
        spark_in - spark object
    """

    with open(unittest_config_path) as config_file:
        unittest_config = yaml.load(config_file, Loader=yaml.FullLoader)

    for file_path_in in unittest_config["local_test_file_names"]:

        copy_local_to_s3(
            os.path.join(
                os.path.abspath(os.path.dirname(__file__)),
                "data/" + file_path_in,
            ),
            unittest_config["s3_in_path"] + file_path_in,
        )

    df = spark_in.read.csv(
        unittest_config["s3_in_path"] + "CATEGORY_DNA_full.txt",
        sep="|",
        header=True,
        quote='"',
    )

    df.write.parquet(
        unittest_config["s3_in_path"] + "CATEGORY_DNA_full/PARQUET/",
        mode="overwrite",
    )


